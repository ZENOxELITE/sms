create table public.courses (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  department text not null,
  credits smallint not null default 3 check (credits > 0),
  program text,
  semester smallint,
  is_sample boolean not null default false,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  constraint courses_semester_range_check
    check (semester is null or semester between 1 and 8)
);

create table public.course_staff (
  course_id bigint not null references public.courses (id) on delete cascade,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  primary key (course_id, profile_id)
);

create table public.enrollments (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses (id) on delete cascade,
  student_id uuid not null references public.profiles (id) on delete cascade,
  term text not null,
  enrolled_at timestamptz not null default now(),
  unique (course_id, student_id, term)
);

create table public.class_sessions (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses (id) on delete cascade,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  location text not null default '',
  check (ends_at > starts_at)
);

create table public.exams (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses (id) on delete cascade,
  title text not null,
  exam_type text not null default 'exam',
  starts_at timestamptz not null,
  location text not null default '',
  created_at timestamptz not null default now()
);

create table public.attendance_records (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.class_sessions (id) on delete cascade,
  student_id uuid not null references public.profiles (id) on delete cascade,
  marked_by uuid references public.profiles (id) on delete set null,
  status text not null check (status in ('present', 'absent', 'late', 'excused')),
  created_at timestamptz not null default now(),
  unique (session_id, student_id)
);

create table public.grades (
  id bigint generated by default as identity primary key,
  course_id bigint not null references public.courses (id) on delete cascade,
  student_id uuid not null references public.profiles (id) on delete cascade,
  grade text not null,
  term text not null,
  published boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (course_id, student_id, term)
);

create table public.invoices (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles (id) on delete cascade,
  description text not null,
  amount numeric(10, 2) not null check (amount >= 0),
  due_date date not null,
  status text not null default 'unpaid' check (status in ('unpaid', 'paid', 'overdue')),
  created_at timestamptz not null default now()
);

create table public.announcements (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  audience text not null default 'all',
  published boolean not null default false,
  published_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.student_requests (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles (id) on delete cascade,
  request_type text not null check (request_type in ('feedback', 'complaint')),
  subject text not null,
  message text not null,
  status text not null default 'submitted'
    check (status in ('submitted', 'in_review', 'resolved')),
  created_at timestamptz not null default now()
);

create index enrollments_student_id_idx on public.enrollments (student_id);
create index attendance_student_id_idx on public.attendance_records (student_id);
create index grades_student_id_idx on public.grades (student_id);
create index invoices_student_id_idx on public.invoices (student_id);
create index announcements_published_at_idx on public.announcements (published_at desc);
create index student_requests_student_id_idx on public.student_requests (student_id);

