create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null,
  username text unique,
  role text not null default 'student'
    check (role in ('student', 'teacher', 'hod', 'admin')),
  department text,
  student_number text unique,
  program text,
  semester smallint,
  is_demo boolean not null default false,
  created_at timestamptz not null default now(),
  constraint profiles_semester_range_check
    check (semester is null or semester between 1 and 8),
  constraint profiles_program_semester_check
    check (
      (program is null and semester is null)
      or (
        role = 'student'
        and program in (
          'BS Cyber Security Technology',
          'BS Software Engineering',
          'BS Software Engineering Technology'
        )
        and semester is not null
        and semester between 1 and 8
      )
    )
);

create table public.departments (
  name text primary key,
  created_at timestamptz not null default now()
);

