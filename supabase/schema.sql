create policy "Users can read their own profile"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()));

create policy "Signed-in users can read departments"
  on public.departments for select to authenticated
  using (true);

create policy "New accounts can create a student profile"
  on public.profiles for insert to authenticated
  with check (id = (select auth.uid()) and role = 'student');

create policy "Students can update their own profile"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()) and role = 'student')
  with check (id = (select auth.uid()) and role = 'student');

create policy "Signed-in users can read courses"
  on public.courses for select to authenticated
  using (true);

create policy "Staff can see their course assignments"
  on public.course_staff for select to authenticated
  using (profile_id = (select auth.uid()));

create policy "Students can read their enrollments"
  on public.enrollments for select to authenticated
  using (student_id = (select auth.uid()));

create policy "Signed-in users can read class sessions"
  on public.class_sessions for select to authenticated
  using (true);

create policy "Students can read their attendance"
  on public.attendance_records for select to authenticated
  using (student_id = (select auth.uid()));

create policy "Assigned staff can record attendance"
  on public.attendance_records for insert to authenticated
  with check (
    marked_by = (select auth.uid())
    and exists (
      select 1
      from public.class_sessions session
      join public.course_staff staff on staff.course_id = session.course_id
      where session.id = session_id and staff.profile_id = (select auth.uid())
    )
  );

create policy "Students can read published grades"
  on public.grades for select to authenticated
  using (student_id = (select auth.uid()) and published);

create policy "Students can read their invoices"
  on public.invoices for select to authenticated
  using (student_id = (select auth.uid()));

create policy "Signed-in users can read published announcements"
  on public.announcements for select to authenticated
  using (published);

create policy "Students can read their own requests"
  on public.student_requests for select to authenticated
  using (student_id = (select auth.uid()));

create policy "Students can submit their own requests"
  on public.student_requests for insert to authenticated
  with check (student_id = (select auth.uid()));
