drop policy if exists "Assigned staff can manage attendance" on public.attendance_records;
create policy "Campus users can read allowed attendance"
  on public.attendance_records for select to authenticated
  using (
    student_id = (select auth.uid())
    or public.current_profile_role() = 'admin'
    or exists (
      select 1 from public.class_sessions s
      where s.id = attendance_records.session_id and public.is_course_staff(s.course_id)
    )
    or exists (
      select 1 from public.class_sessions s
      join public.courses c on c.id = s.course_id
      where s.id = attendance_records.session_id
        and public.current_profile_role() = 'hod'
        and c.department = public.current_profile_department()
    )
  );
create policy "Assigned staff can manage attendance"
  on public.attendance_records for all to authenticated
  using (
    public.current_profile_role() = 'admin'
    or exists (
      select 1 from public.class_sessions s
      where s.id = attendance_records.session_id and public.is_course_staff(s.course_id)
    )
  )
  with check (
    (public.current_profile_role() = 'admin' or public.is_course_staff((
      select s.course_id from public.class_sessions s where s.id = session_id
    )))
    and marked_by = (select auth.uid())
    and exists (
      select 1 from public.enrollments e
      join public.class_sessions s on s.course_id = e.course_id
      where s.id = session_id and e.student_id = attendance_records.student_id
    )
  );

