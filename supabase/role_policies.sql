create or replace function public.current_profile_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.role from public.profiles p where p.id = (select auth.uid())
$$;

create or replace function public.current_profile_department()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.department from public.profiles p where p.id = (select auth.uid())
$$;

create or replace function public.is_course_staff(target_course_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.course_staff cs
    where cs.course_id = target_course_id and cs.profile_id = (select auth.uid())
  )
$$;

