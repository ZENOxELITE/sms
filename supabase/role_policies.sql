drop policy if exists "Students can update their own non-role profile fields" on public.profiles;
create policy "Campus staff can read allowed profiles"
  on public.profiles for select to authenticated
  using (
    id = (select auth.uid())
    or public.current_profile_role() = 'admin'
    or (
      public.current_profile_role() = 'hod'
      and department = public.current_profile_department()
    )
    or exists (
      select 1 from public.enrollments e
      join public.course_staff cs on cs.course_id = e.course_id
      where e.student_id = profiles.id and cs.profile_id = (select auth.uid())
    )
  );
create policy "Administrators can manage profiles"
  on public.profiles for all to authenticated
  using (public.current_profile_role() = 'admin')
  with check (public.current_profile_role() = 'admin');
create policy "Students can update their own non-role profile fields"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()) and role = 'student')
  with check (id = (select auth.uid()) and role = 'student');

