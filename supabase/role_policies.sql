  on public.grades for all to authenticated
  using (
    public.current_profile_role() = 'admin'
    or public.is_course_staff(course_id)
  )
  with check (
    (public.current_profile_role() = 'admin' or public.is_course_staff(course_id))
    and exists (
      select 1 from public.enrollments e
      where e.course_id = grades.course_id and e.student_id = grades.student_id
    )
  );

