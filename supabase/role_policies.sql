create or replace function public.current_profile_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.role from public.profiles p where p.id = (select auth.uid())
$$;

create or replace function public.current_profile_department()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.department from public.profiles p where p.id = (select auth.uid())
$$;

create or replace function public.is_course_staff(target_course_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.course_staff cs
    where cs.course_id = target_course_id and cs.profile_id = (select auth.uid())
  )
$$;

alter table public.profiles add column if not exists username text;
create unique index if not exists profiles_username_lower_unique
  on public.profiles (lower(username))
  where username is not null;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'profiles_username_format_check'
      and conrelid = 'public.profiles'::regclass
  ) then
    alter table public.profiles
      add constraint profiles_username_format_check
      check (
        username is null
        or (
          username = lower(username)
          and username ~ '^[a-z0-9][a-z0-9._-]{2,31}$'
        )
      );
  end if;
end
$$;

